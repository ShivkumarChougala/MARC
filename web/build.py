from pathlib import Path
import re
import hashlib
import shutil
import tempfile

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "dist"
MARKER = ".marc-generated-build"
COMPONENT = re.compile(
    r'<div\b\s+data-component=["\']([a-zA-Z0-9_-]+)["\']\s*>\s*</div>',
    re.I
)

def render(text, stack=()):
    def replace(match):
        name = match.group(1)
        if name in stack:
            raise SystemExit("Circular component: " + name)
        source = ROOT / "components" / (name + ".html")
        if not source.is_file():
            raise SystemExit("Missing component: " + name)
        return render(
            source.read_text(encoding="utf-8"),
            stack + (name,)
        )
    return COMPONENT.sub(replace, text)

if not (ROOT / "index.html").is_file():
    raise SystemExit("Website index.html not found.")

if OUTPUT.exists() and not (OUTPUT / MARKER).is_file():
    raise SystemExit("dist already exists and is not a MARC build. Nothing changed.")

with tempfile.TemporaryDirectory(prefix="marc-build-") as temporary:
    staged = Path(temporary) / "dist"
    staged.mkdir()

    for name in ["assets", "css", "js", "docs"]:
        source = ROOT / name
        if source.is_dir():
            shutil.copytree(source, staged / name)

    for source in ROOT.glob("*.html"):
        shutil.copy2(source, staged / source.name)

    for name in ["_headers", "_redirects", "robots.txt", "sitemap.xml"]:
        source = ROOT / name
        if source.is_file():
            shutil.copy2(source, staged / name)

    # Fingerprint delivered bytes so a CSS/JS update cannot reuse a stale URL.
    fingerprints = {}
    resource = re.compile(
        r"(?<=[\"'(\s])(/?(?:assets|css|js)/[\w./-]+)(?:\?v=[^\s\"'<>),]+)?"
    )

    def version_resources(text):
        def replace(match):
            path = match.group(1)
            version = fingerprints.get(path.lstrip("/"))
            return path + "?v=" + version if version else match.group(0)
        return resource.sub(replace, text)

    for asset in sorted((staged / "assets").rglob("*")):
        if asset.is_file():
            fingerprints[asset.relative_to(staged).as_posix()] = hashlib.sha256(asset.read_bytes()).hexdigest()[:12]
    for directory in ["css", "js"]:
        for asset in sorted((staged / directory).glob("*")):
            if not asset.is_file():
                continue
            asset.write_text(version_resources(asset.read_text(encoding="utf-8")), encoding="utf-8")
            fingerprints[asset.relative_to(staged).as_posix()] = hashlib.sha256(asset.read_bytes()).hexdigest()[:12]

    pages = list(staged.glob("*.html"))
    pages += list((staged / "docs").rglob("*.html"))

    for page in pages:
        html = version_resources(render(page.read_text(encoding="utf-8")))
        if re.search(r'<[^>]+\bdata-component\s*=', html, re.I):
            raise SystemExit("Unresolved component in " + page.name)
        page.write_text(html, encoding="utf-8")

    home = (staged / "index.html").read_text(encoding="utf-8")
    if not re.search(r"<h1\b", home, re.I):
        raise SystemExit("Homepage heading missing. Build stopped.")

    (staged / MARKER).write_text(
        "Generated by build.py; edit source files instead.\n"
    )

    if OUTPUT.exists():
        shutil.rmtree(OUTPUT)
    shutil.copytree(staged, OUTPUT)

    print(f"PASS: built {len(pages)} pages with components included.")
    print("Output: dist/ — original source files preserved.")
